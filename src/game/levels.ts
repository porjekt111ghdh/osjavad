export const LEVELS: Level[] = RAW.split("\n").map((line, index) => {
  try {
    return buildLevel(index + 1, line);
  } catch (error) {
    const message = error instanceof Error ? error.message : "خطای ناشناخته";
    throw new Error(`مرحله ${index + 1}: ${message}`);
  }
});

export const CHAPTERS = [
  "کوچهٔ اول",
  "بازار عصر",
  "شب کارون",
  "عطر نارنج",
  "خانهٔ پدری",
  "کاروان‌سرا",
  "باغ انار",
  "افق طلایی",
  "دفتر جواد",
  "تاج واژه‌ها",
] as const;

export function chapterOf(levelId: number): string {
  return CHAPTERS[Math.floor((levelId - 1) / 20)] ?? CHAPTERS[0];
}
